"""Define the `dirdiff agent` terminal commands used by review agents.

## Public interface

`agent_app` is the Typer sub-application that `dirdiff.cli.base`, the sole
importer of this private module, mounts as `dirdiff agent`. Every command takes a required `--session PATH` and performs
exactly one explicit step of the agent workflow: `init`, `capture`, `reviews`,
`threads`, `show`, `news`, `wait`, `find`, `comment`, `resolve`, `reopen`,
`edit`, `delete-comment`, and `delete-thread`.

## Purpose and boundaries

The module is the only client of the `/api/agent/*` HTTP boundary specified in
`spec/reviews.md`. It exists so that an LLM agent in a terminal never has to
write HTTP code, track ids, or quote long Markdown through a shell: output is
compact plain text that names repository paths, thread titles, who a thread
waits on, and UTC timestamps.

It owns one JSON session file per agent, whose path the caller names on every
command. The file records the server URL, the agent UUID, the Profile id, the
role the agent speaks as, the captured Tab descriptor and repository id, the
latest Snapshot id and directory, and the activity cursor. The module reads
and writes that file only; it consults no environment variable and has no
default location.

The commands never retry, substitute defaults, or hide failures: a rejected
operation prints the server's plain-text body to standard error and exits
non-zero. The module must not own review state, parse repository content, or
duplicate server-side validation beyond what is needed to build a request.
"""

