class Wire(BaseModel):
    """Base of every response model: the complete agent wire shape.

    Each model lists every field the server sends, so a renamed, missing, or
    additional field is a contract violation that fails validation instead of
    being ignored. It adds no fields or behavior.
    """

    model_config = ConfigDict(extra="forbid")


class Session(BaseModel):
    """One agent's persisted state, exactly as stored in its session file.

    Every field is required. A file that is missing a field, carries an unknown
    one, or holds a different type is malformed and rejected on load. `tab` is
    the Tab descriptor accepted unchanged by `capture`; `cursor` is the
    activity id after which `news` and `wait` report events.
    """

    model_config = ConfigDict(extra="forbid")

    server_url: str
    """Origin of the dirdiff server, as `onboard` reported it."""

    agent_uuid: str
    """Compact lowercase UUID generated by `init`; the identity key of this agent."""

    profile_id: int
    """Profile id sent as the actor of every action."""

    name: str
    """Display name registered for the Profile."""

    role: Literal["author", "reviewer"]
    """Role stated on every `create-thread`, `comment`, and `reopen`."""

    model: str
    """Model name registered for the Profile."""

    harness: str
    """Harness name registered for the Profile."""

    project_id: int
    """Repository (Mark) id taken from the capture."""

    tab: dict[str, JsonValue]
    """Tab descriptor, sent unchanged to `capture`."""

    snapshot_id: str
    """Snapshot id as of the latest capture."""

    snapshot_dir: str
    """Absolute read-only directory of the latest Snapshot."""

    cursor: int
    """Activity id after which `news` and `wait` report events."""


